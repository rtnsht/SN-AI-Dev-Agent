/**
 * Code Generator
 * Generates ServiceNow artifacts (Business Rules, Script Includes, etc.)
 * Uses templates and AI-assisted code generation
 */

import { logger } from '../utils/logger.js';
import fs from 'fs';
import path from 'path';
import { v4 as uuidv4 } from 'uuid';

export class CodeGenerator {
  constructor(solution, analysis, context = null) {
    this.solution = solution;
    this.analysis = analysis;
    this.context = context;
    this.generatedArtifacts = [];
  }

  /**
   * Generate all artifacts defined in the solution
   */
  async generateAll() {
    logger.info('Generating ServiceNow artifacts...');
    
    for (const artifact of this.solution.artifacts) {
      logger.info(`  Generating ${artifact.type}: ${artifact.name}`);
      const generated = await this.generateArtifact(artifact);
      this.generatedArtifacts.push(generated);
    }

    logger.success(`Generated ${this.generatedArtifacts.length} artifacts`);
    return this.generatedArtifacts;
  }

  async generateArtifact(artifact) {
    const generators = {
      'script_include': this.generateScriptInclude.bind(this),
      'business_rule': this.generateBusinessRule.bind(this),
      'client_script': this.generateClientScript.bind(this),
      'flow': this.generateFlow.bind(this),
      'ui_policy': this.generateUIPolicy.bind(this),
      'ui_action': this.generateUIAction.bind(this),
      'scheduled_job': this.generateScheduledJob.bind(this),
      'scripted_rest_api': this.generateScriptedRESTAPI.bind(this)
    };

    const generator = generators[artifact.type];
    if (!generator) {
      logger.warn(`No generator for artifact type: ${artifact.type}`);
      return null;
    }

    return generator(artifact);
  }

  generateScriptInclude(artifact) {
    const className = artifact.name.replace(/\s+/g, '');
    
    const script = `/**
 * ${artifact.description || artifact.name}
 * Auto-generated by SN AI Dev
 * 
 * @class ${className}
 */
var ${className} = Class.create();
${className}.prototype = {
    
    /**
     * Initialize the ${className}
     */
    initialize: function() {
        this.LOG_SOURCE = '${className}';
    },

    /**
     * Main processing method
     * @param {GlideRecord} record - The record to process
     * @returns {Object} Processing result
     */
    process: function(record) {
        try {
            // TODO: Implement business logic based on requirements
            // Requirement: ${this.analysis.originalText}
            
            gs.info(this.LOG_SOURCE + ': Processing record ' + record.getUniqueValue());
            
            var result = {
                success: true,
                message: 'Processing complete'
            };
            
            return result;
        } catch (ex) {
            gs.error(this.LOG_SOURCE + ': Error - ' + ex.message);
            return {
                success: false,
                message: ex.message
            };
        }
    },

    /**
     * Validate input data
     * @param {Object} data - Data to validate
     * @returns {Boolean} Validation result
     */
    validate: function(data) {
        if (!data) {
            return false;
        }
        // TODO: Add validation logic
        return true;
    },

    type: '${className}'
};`;

    return {
      type: 'script_include',
      name: className,
      apiName: className,
      script,
      clientCallable: false,
      active: true,
      sysId: this.generateTempSysId(),
      table: 'sys_script_include',
      metadata: artifact
    };
  }

  generateBusinessRule(artifact) {
    const name = artifact.name;
    const table = artifact.table || 'incident';
    const when = artifact.when || 'after';
    
    const script = `/**
 * Business Rule: ${name}
 * Table: ${table}
 * When: ${when}
 * Auto-generated by SN AI Dev
 */
(function executeRule(current, previous /*null when async*/) {
    
    try {
        // Requirement: ${this.analysis.originalText}
        
        // Check if this is a relevant update
        if (current.operation() == 'insert' || current.operation() == 'update') {
            
            // TODO: Implement business logic
            gs.info('Business Rule ${name} triggered on ' + current.getTableName());
            
            // Example: Call Script Include for processing
            // var utils = new ${this.toPascalCase(this.analysis.title)}Utils();
            // utils.process(current);
        }
        
    } catch (ex) {
        gs.error('Error in Business Rule ${name}: ' + ex.message);
    }

})(current, previous);`;

    return {
      type: 'business_rule',
      name,
      collection: table,
      when,
      order: 100,
      script,
      active: true,
      actionInsert: artifact.operations?.includes('insert') ?? true,
      actionUpdate: artifact.operations?.includes('update') ?? true,
      actionDelete: artifact.operations?.includes('delete') ?? false,
      actionQuery: false,
      condition: '',
      sysId: this.generateTempSysId(),
      table: 'sys_script',
      metadata: artifact
    };
  }

  generateClientScript(artifact) {
    const name = artifact.name;
    const table = artifact.table || 'incident';
    const scriptType = artifact.scriptType || 'onLoad';
    
    const script = `/**
 * Client Script: ${name}
 * Table: ${table}
 * Type: ${scriptType}
 * Auto-generated by SN AI Dev
 */
function ${scriptType}() {
    
    try {
        // Requirement: ${this.analysis.originalText}
        
        // TODO: Implement client-side logic
        console.log('Client Script ${name} executed');
        
    } catch (ex) {
        console.error('Error in Client Script ${name}: ' + ex.message);
    }
}`;

    return {
      type: 'client_script',
      name,
      table,
      scriptType,
      script,
      active: true,
      uiType: 'Desktop',
      sysId: this.generateTempSysId(),
      tableName: 'sys_script_client',
      metadata: artifact
    };
  }

  generateFlow(artifact) {
    return {
      type: 'flow',
      name: artifact.name,
      description: artifact.description || `Flow for ${this.analysis.title}`,
      trigger: artifact.trigger || 'record_update',
      active: false, // Flows should be manually activated
      sysId: this.generateTempSysId(),
      table: 'sys_hub_flow',
      definition: {
        // Flow definitions are complex - provide a structure
        trigger: { type: artifact.trigger || 'record_update' },
        actions: [],
        conditions: []
      },
      metadata: artifact
    };
  }

  generateUIPolicy(artifact) {
    return {
      type: 'ui_policy',
      name: artifact.name,
      table: artifact.table,
      shortDescription: artifact.name,
      active: true,
      onLoad: true,
      reverseIfFalse: true,
      conditions: '',
      sysId: this.generateTempSysId(),
      tableName: 'sys_ui_policy',
      metadata: artifact
    };
  }

  generateUIAction(artifact) {
    const script = `// UI Action: ${artifact.name}\n// TODO: Implement action logic`;
    return { type: 'ui_action', name: artifact.name, table: artifact.table, 
             script, active: true, sysId: this.generateTempSysId(), metadata: artifact };
  }

  generateScheduledJob(artifact) {
    const script = `// Scheduled Job: ${artifact.name}\ngs.info('Running scheduled job');`;
    return { type: 'scheduled_job', name: artifact.name, script, 
             active: false, sysId: this.generateTempSysId(), metadata: artifact };
  }

  generateScriptedRESTAPI(artifact) {
    return { type: 'scripted_rest_api', name: artifact.name, 
             sysId: this.generateTempSysId(), metadata: artifact };
  }

  generateTempSysId() { return uuidv4().replace(/-/g, ''); }
  toPascalCase(str) { return str.replace(/(?:^|\s)\w/g, m => m.toUpperCase()).replace(/\s+/g, ''); }

  exportArtifacts(outputDir) {
    if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });
    this.generatedArtifacts.forEach(artifact => {
      const dir = path.join(outputDir, artifact.type + 's');
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      const filePath = path.join(dir, `${artifact.name.replace(/\s+/g, '_')}.json`);
      fs.writeFileSync(filePath, JSON.stringify(artifact, null, 2));
    });
    logger.success(`Artifacts exported to ${outputDir}`);
  }
}

export default CodeGenerator;

